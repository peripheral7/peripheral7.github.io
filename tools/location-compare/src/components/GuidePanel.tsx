import { useEffect } from 'react'
import { MAX_HUBS } from '../data'
import { TRANSIT_PARTS, WALK_LIMIT, WALK_ONLY, WALK_ZONE } from '../scoring'
import { CAT_BASE, CAT_FOUR, CAT_MAX, CAT_RADIUS_M, FIELD_RADIUS_M, PHOTO_MAX_SIDE, PHOTO_QUALITY, PHOTO_VALID_DAYS } from '../cats'

const fmt1 = (x: number) => (Math.round(x * 10) / 10).toString()

// 화면 안의 "계산 방식" 안내. 더 자세한 설명과 예시는 tools/location-compare/README.md.
export function GuidePanel({ onClose }: { onClose: () => void }) {
  useEffect(() => {
    const onKey = (e: KeyboardEvent) => { if (e.key === 'Escape') onClose() }
    window.addEventListener('keydown', onKey)
    return () => window.removeEventListener('keydown', onKey)
  }, [onClose])
  const pct = (x: number) => `${Math.round(x * 100)}%`

  return (
    <div className="overlay" onClick={onClose}>
      <section className="glass drawer guide" role="dialog" aria-modal="true" aria-label="계산 방식 안내" onClick={(e) => e.stopPropagation()}>
        <div className="drawer-head"><div><small>HOW IT WORKS</small><h2>기능과 계산 방식</h2></div><button className="close" aria-label="닫기" onClick={onClose}>×</button></div>

        <h3>1. 화면 구성</h3>
        <ul>
          <li><b>지도</b> — 번호 원은 후보지(숫자 = 종합 순위), 이모지 원은 주요 목적지(🏫 학교 · 🏠 본가 · 🏢 직장 · 🚉 교통센터). 후보지를 고르면 그 후보지와 목적지가 모두 들어오도록 지도가 확대·이동하고, 목적지까지 점선을 긋습니다. 오른쪽 위 "장단점 기준"(또는 목적지 핀)으로 목적지를 고르면 후보지 옆에 그 목적지 기준 순위와 장점(＋ 도보권·대중교통 최적·차량 이동 최적·환승 없음·대기 최소)·단점(－ 도보 {WALK_LIMIT}분 초과·대중교통 불리·출퇴근 정체·환승 많음)을 글자로 보여 줍니다(도보 {WALK_ONLY}분 이내면 대중교통 항목은 말하지 않음). 그 옆 <b>"후보지 한번에 보기"</b>는 모든 후보지가 고르게 들어오도록 지도를 맞춥니다. 평소엔 고른 후보지에만, 동네가 구분될 만큼 확대하면(확대 14단계 이상) 보이는 모든 후보지에. 네이버 지도 키가 없으면 밝은 OSM 지도로 보입니다.</li>
          <li><b>검색창(지도 위)</b> — 아파트·주소·학교·회사를 한 창에서 찾고, 결과에서 바로 "후보지로" 또는 "목적지로"(목적지가 2곳이면 "학교 대신"처럼 바꿀 곳을 고름) 넣습니다. Enter·검색 단추를 누를 때만 검색합니다.</li>
          <li><b>이동수단별 점수(왼쪽)</b> — 고른 후보지의 종합 점수 게이지와 대중교통·차량·도보 눈금 막대(목적지 점수를 월 왕복 비율로 평균). 오른쪽 위 가중치는 합 100 기준 비율입니다. <b>이 카드를 누르면</b> 그 칸 오른쪽에 수단 가중치 창이 열립니다. 가중치는 숫자로 넣고(100을 넘어도 됨) 계산은 합에 대한 비율로 합니다.</li>
          <li><b>선택한 후보지(왼쪽 아래)</b> — 맨 위 ‹ › 로 앞·뒤 순위 후보지, 맨 아래 순위 숫자로 바로 고르기, 이름·주소·보증금/월세. 내용이 많으면 박스 안에서 스크롤. "수정"으로 이름·보증금·월세 바꾸기(삭제도 여기). <b>주요 목적지 칸을 누르면</b> 월 왕복 횟수 창, × 로 목적지 빼기.</li>
          <li><b>입지 요인(오른쪽 위)</b> — 오른쪽 위 ⚙ 에서 쓸 지수를 고릅니다. 지금은 <b>길고양이 지수</b>(켜면 점수 줄과 사진·등록 링크, 아래 후보지 카드에도 한 줄). 도보 5분 상권·산책·평화로움·쾌적함은 준비 중.</li>
          <li><b>후보지별 비교(아래 카드)</b> — 후보지 카드를 가로로 놓고 줄을 맞췄습니다. 같은 줄을 옆으로 읽으면 대기·정류장까지 도보·환승, 출퇴근/낮 시간 차이를 후보지끼리 비교할 수 있습니다. 가장 높은 점수는 초록색. 보증금/월세 줄의 연한 글씨는 <b>보증금 1,000만원으로 맞춘 월세</b>(전월세 전환율 연 6% — 보증금 1,000만원 차이 = 월 5만원). 이름 옆 ✎ 로 이름 바꾸기. 양옆 카드는 추천 매물·근처 카페·식당 자리(준비 중).</li>
          <li>바꾼 후보지·목적지·선호도는 이 브라우저에만 저장됩니다.</li>
        </ul>

        <h3>2. 이동 시간(가상 추정)</h3>
        <p><b>두 지점의 직선거리(km)</b>로 추정합니다. 단, <b>차량</b>은 네이버 길찾기로 미리 잰 값(src/routes.json)이 있으면 그 값을 씁니다(카드에 "네이버 실측" 표시). 지금은 기본 후보지의 여유 시간대만 실측되어 있고(출퇴근은 실측 여유 × 1.52 + 4분), 검색으로 넣은 후보지·목적지는 추정입니다.</p>
        <ul>
          <li>도보 = 거리 ÷ 시속 4.7km</li>
          <li>대중교통 = 역·정류장까지 도보(4분 + 거리×0.7분, 3~18분) + 대기(5분 + 거리÷6, 최대 +7분) + 탑승(시속 22km) + 환승(3km 이하 0회 · 12km 이하 1회 · 그 이상 2회, 1회당 5분)</li>
          <li>차량 여유 = 거리 ÷ 시속 31km + 3분 · 출퇴근 = 여유 × 1.52 + 4분</li>
        </ul>

        <h3>3. 수단별 점수 (10점 만점)</h3>
        <ul>
          <li><b>대중교통 — 후보지끼리 상대 비교.</b> 같은 방문지를 두고 대기·도보·환승 각각에서 가장 좋은 후보지가 10점, 나머지는 <code>10 × 최솟값 ÷ 내 값</code>(환승은 0회도 나눌 수 있게 각각 +1). 세 항목을 대기 {pct(TRANSIT_PARTS.wait)} · 도보 {pct(TRANSIT_PARTS.access)} · 환승 {pct(TRANSIT_PARTS.transfers)}로 합칩니다. 탑승 시간은 점수에 넣지 않고 표시만 합니다.</li>
          <li><b>차량 — 후보지끼리 상대 비교.</b> 정체 배율 = 출퇴근 ÷ 여유 시간. 배율이 가장 낮은 후보지가 10점, 나머지는 <code>10 × 최저 배율 ÷ 내 배율</code>.</li>
          <li><b>도보 — 시간만.</b> 5분 이하 10점, {WALK_LIMIT}분 0점 사이 직선. {WALK_ZONE}분 이하는 <b>도보권</b>. <b>{WALK_LIMIT}분을 넘으면 카드에 시간·점수를 적지 않습니다.</b></li>
        </ul>

        <h3>4. 가중치와 종합 점수</h3>
        <ul>
          <li><b>방문지 점수</b> = 수단별 점수를 수단 가중치로 가중 평균. 가중치는 합이 100이 아니어도(넘어도) <b>합에 대한 비율</b>로 씁니다(예: 120·60·20 → 60%·30%·10%).</li>
          <li><b>도보 {WALK_ONLY}분 이내</b> — 그 방문지는 걸어간다고 보고 <b>대중교통을 빼고</b> 차량·도보 가중치만으로 다시 나눕니다(카드에 "걸어가니 대중교통 제외").</li>
          <li><b>도보가 {WALK_LIMIT}분을 넘는 경우</b> — 그 방문지에 걸어갈 수 있는 후보지가 하나라도 있으면, 못 걷는 후보지는 도보 <b>0점</b>으로 계산합니다(빼 버리면 못 걷는 쪽이 오히려 유리해지기 때문). 아무 후보지도 걸어갈 수 없는 방문지(예: 본가)는 도보를 빼고 대중교통·차량 가중치만으로 다시 나눕니다.</li>
          <li><b>종합 점수</b> = 방문지 점수를 <b>월 왕복 횟수 비율</b>로 가중 평균(카드의 "반영 %"). 횟수가 모두 0이면 방문지를 똑같이 봅니다.</li>
          <li>순위는 종합 점수 순입니다. 상대 비교라서 후보지를 바꾸면 다른 후보지의 대중교통·차량 점수도 바뀔 수 있습니다.</li>
        </ul>

        <h3>5. 길고양이 지수 (선택, 0~10점)</h3>
        <ul>
          <li><b>무엇을 세나</b> — 후보지에서 <b>반경 {CAT_RADIUS_M}m</b> 안에 등록된 길고양이 수 n(유효한 사진이 한 장 이상인 고양이만). 참여자 수 u = 그 고양이들에 유효한 사진을 올린 서로 다른 사용자 수.</li>
          <li><b>점수</b> — 0마리 0점 · <b>1마리 {CAT_BASE}점</b> · 2마리 {fmt1(CAT_BASE + (CAT_FOUR - CAT_BASE) / 3)}점 · 3마리 {fmt1(CAT_BASE + (2 * (CAT_FOUR - CAT_BASE)) / 3)}점 · <b>4마리 {CAT_FOUR}점</b>(한 마리당 {fmt1((CAT_FOUR - CAT_BASE) / 3)}점씩). 4마리 이상이면 <code>{CAT_FOUR} + 0.5 × (u − 1)</code>, 최대 <b>{CAT_MAX}점</b>(참여자 5명 이상). 고양이가 많아도 참여자가 한 명뿐이면 {CAT_FOUR}점에서 멈춥니다.</li>
          <li><b>사진</b> — 등록 후 <b>{PHOTO_VALID_DAYS}일(약 2달)</b> 동안만 유효. 지나면 그 사진은 지수에서 빠지고, 고양이의 사진이 모두 만료되면 그 고양이도 셈에서 빠집니다. <b>한 사람이 고양이 한 마리에 사진 한 장</b>만 올릴 수 있습니다.</li>
          <li><b>현장에서만</b> — 등록은 내 현재 위치(GPS, 정확도 80m 이내)가 고양이 위치로 기록되고 지도에서 직접 고를 수 없으며, 사진도 카메라로 바로 찍습니다. 이미 등록된 고양이에 사진을 더하려면 {FIELD_RADIUS_M}m 안에 있어야 합니다. 출몰 시간대(새벽·아침·낮·저녁·밤)와 특징(털색·성격 등)을 함께 적습니다.</li>
          <li><b>사진 크기</b> — 긴 변이 {PHOTO_MAX_SIDE}px 를 넘으면 그 크기로 줄여 좋은 화질(JPEG {Math.round(PHOTO_QUALITY * 100)})로 저장합니다. 사진의 위치 정보(EXIF)는 지워집니다.</li>
          <li><b>종합 점수와의 관계</b> — 길고양이 지수는 따로 보는 지수이며 이동수단 종합 점수·순위에는 섞지 않습니다.</li>
          <li><b>서버 업로드는 꺼져 있습니다</b> — 서버가 없어서 등록한 고양이는 이 브라우저에만 저장되고 다른 사용자에게 보이지 않습니다. 그래서 지금은 참여자가 대개 나 한 명이며, 서버가 생기면 사용자가 합쳐져 위 계산이 그대로 적용됩니다.</li>
        </ul>

        <h3>6. 한계</h3>
        <ul>
          <li>대중교통·도보는 실제 노선·배차를 반영하지 않은 추정입니다(네이버 클라우드 지도 API 에는 대중교통 길찾기가 없습니다).</li>
          <li>지금의 차량 공식(출퇴근 = 여유 × 1.52 + 4분)에서는 거리가 짧을수록 정체 배율이 커져, 가까운 후보지의 차량 점수가 낮게 나옵니다. 실제 교통 자료가 들어오면 사라질 성질입니다.</li>
          <li>후보지 주소는 임시 입력이며, 주소 검색은 추후 추가 예정입니다.</li>
        </ul>
      </section>
    </div>
  )
}
